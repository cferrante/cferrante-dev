// Command siteconfig writes web/dist/config.js, the page's build-time
// settings (design §14): the site and assistant names and any overrides of
// the friendly error messages. Settings come from the environment (or .env);
// MESSAGES_FILE names a JSON file of message overrides.
//
// The page in production is static files, so build-time settings keep it
// static: no request to Lambda just to learn its own name.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"log"
	"os"
	"path/filepath"

	cfg "github.com/cferrante/cferrante-dev/orchestrator/config"
	"github.com/cferrante/cferrante-dev/orchestrator/wording"
)

type siteConfig struct {
	SiteName      string            `json:"siteName"`
	AssistantName string            `json:"assistantName"`
	Messages      map[string]string `json:"messages"`
}

// generate returns the contents of config.js. A bad MESSAGES_FILE stops the
// build, so a typo can't silently fall back to the default.
func generate(getenv cfg.Getenv, readFile func(string) ([]byte, error)) ([]byte, error) {
	env := cfg.New(getenv)
	c := siteConfig{
		SiteName:      env.String("SITE_NAME", "cferrante.dev"),
		AssistantName: env.String("ASSISTANT_NAME", "Context Concierge"),
		Messages:      map[string]string{},
	}
	// The same file and validation as the server's (orchestrator/wording);
	// an unknown key, empty value or bad placeholder stops the build.
	w, err := wording.Load(env.String("MESSAGES_FILE", ""), readFile)
	if err != nil {
		return nil, err
	}
	c.Messages = w.Overrides()
	// json.Marshal escapes <, > and & (as <...), so no value can close a
	// script tag or inject markup; the page also shows every value as text.
	body, err := json.Marshal(c)
	if err != nil {
		return nil, err
	}
	return []byte("// Generated by orchestrator/cmd/siteconfig from the environment; don't edit.\n" +
		"export default " + string(body) + ";\n"), nil
}

func run(args []string, getenv cfg.Getenv, out io.Writer) error {
	fs := flag.NewFlagSet("siteconfig", flag.ContinueOnError)
	path := fs.String("out", "web/dist/config.js", "file to write")
	if err := fs.Parse(args); err != nil {
		return err
	}
	js, err := generate(getenv, os.ReadFile)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(*path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(*path, js, 0o644); err != nil {
		return err
	}
	fmt.Fprintf(out, "siteconfig: wrote %s\n", *path)
	return nil
}

func main() {
	getenv, err := cfg.WithDotEnv(".env", os.Getenv)
	if err == nil {
		err = run(os.Args[1:], getenv, os.Stdout)
	}
	if err != nil {
		log.Fatal("siteconfig: ", err)
	}
}
