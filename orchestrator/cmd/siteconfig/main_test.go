package main

import (
	"encoding/json"
	"errors"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func envOf(m map[string]string) func(string) string { return func(k string) string { return m[k] } }

func files(m map[string]string) func(string) ([]byte, error) {
	return func(p string) ([]byte, error) {
		if v, ok := m[p]; ok {
			return []byte(v), nil
		}
		return nil, os.ErrNotExist
	}
}

// parse reads back the object a generated module exports.
func parse(t *testing.T, js []byte) map[string]any {
	t.Helper()
	s := string(js)
	if !strings.HasPrefix(s, "// Generated by orchestrator/cmd/siteconfig") || !strings.Contains(s, "export default ") {
		t.Fatalf("not a generated module:\n%s", s)
	}
	body := strings.TrimSuffix(strings.TrimSpace(s[strings.Index(s, "export default ")+len("export default "):]), ";")
	var v map[string]any
	if err := json.Unmarshal([]byte(body), &v); err != nil {
		t.Fatalf("exported value isn't JSON: %v\n%s", err, body)
	}
	return v
}

func TestDefaults(t *testing.T) {
	js, err := generate(envOf(nil), files(nil))
	if err != nil {
		t.Fatal(err)
	}
	v := parse(t, js)
	if v["siteName"] != "cferrante.dev" || v["assistantName"] != "Context Concierge" {
		t.Errorf("defaults = %v", v)
	}
	if m, _ := v["messages"].(map[string]any); len(m) != 0 {
		t.Errorf("messages = %v, want none (the page's defaults apply)", m)
	}
}

func TestEnvironmentAndMessagesFile(t *testing.T) {
	js, err := generate(
		envOf(map[string]string{"SITE_NAME": "example.org", "ASSISTANT_NAME": "Concierge", "MESSAGES_FILE": "m.json"}),
		files(map[string]string{"m.json": `{"network": "{assistant} is offline.", "timeout": "Too slow, sorry."}`}))
	if err != nil {
		t.Fatal(err)
	}
	v := parse(t, js)
	m := v["messages"].(map[string]any)
	if v["siteName"] != "example.org" || v["assistantName"] != "Concierge" ||
		m["network"] != "{assistant} is offline." || m["timeout"] != "Too slow, sorry." || len(m) != 2 {
		t.Errorf("config = %v", v)
	}
}

func TestBadMessagesFilesStopTheBuild(t *testing.T) {
	for name, tc := range map[string]struct{ content, want string }{
		"typo in a key": {`{"timout": "x"}`, "timout"},
		"empty message": {`{"network": "  "}`, "network"},
		"not a string":  {`{"network": 3}`, "JSON"},
		"not JSON":      {`{"network":`, "JSON"},
	} {
		_, err := generate(envOf(map[string]string{"MESSAGES_FILE": "m.json"}), files(map[string]string{"m.json": tc.content}))
		if err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("%s: err = %v, want it to mention %q", name, err, tc.want)
		}
	}
	_, err := generate(envOf(map[string]string{"MESSAGES_FILE": "missing.json"}), files(nil))
	if !errors.Is(err, os.ErrNotExist) {
		t.Errorf("missing file: err = %v", err)
	}
}

// A name containing quotes or markup must stay inert data in the module.
func TestValuesCannotBreakOutOfTheModule(t *testing.T) {
	evil := `"; alert(1); //</script><b>`
	js, err := generate(envOf(map[string]string{"ASSISTANT_NAME": evil}), files(nil))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(js), "</script>") || strings.Contains(string(js), "<b>") {
		t.Errorf("markup not escaped:\n%s", js)
	}
	if v := parse(t, js); v["assistantName"] != evil {
		t.Errorf("round trip = %q", v["assistantName"])
	}
}

func TestRunWritesTheFile(t *testing.T) {
	out := filepath.Join(t.TempDir(), "dist", "config.js")
	var log strings.Builder
	if err := run([]string{"-out", out}, envOf(map[string]string{"ASSISTANT_NAME": "Concierge"}), &log); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(out)
	if err != nil || parse(t, b)["assistantName"] != "Concierge" || !strings.Contains(log.String(), out) {
		t.Errorf("file %q, err %v, log %q", b, err, log.String())
	}
}

// The retrieval wording (step 5.3a) goes through the same file, with the
// same validation as the server's (orchestrator/wording).
func TestRetrievalWordingReachesThePage(t *testing.T) {
	js, err := generate(envOf(map[string]string{"MESSAGES_FILE": "m.json"}),
		files(map[string]string{"m.json": `{"retrieval_card": "{excerpts} (score {score})", "excerpt_other": "snippets"}`}))
	if err != nil {
		t.Fatal(err)
	}
	m := parse(t, js)["messages"].(map[string]any)
	if m["retrieval_card"] != "{excerpts} (score {score})" || m["excerpt_other"] != "snippets" {
		t.Errorf("messages = %v", m)
	}
	_, err = generate(envOf(map[string]string{"MESSAGES_FILE": "m.json"}),
		files(map[string]string{"m.json": `{"retrieval_card": "{exerpts}"}`}))
	if err == nil || !strings.Contains(err.Error(), "{exerpts}") {
		t.Errorf("misspelt placeholder: err = %v, want the build stopped", err)
	}
}
